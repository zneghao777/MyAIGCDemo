export function errorMessage(error: unknown): ErrorCopy {
  if (error instanceof ApiError) {
    const known = errors[error.code || ""];
    if (known) return { title: known[0], detail: known[1], action: "刷新页面" };
    return /[\u3400-\u9fff]/.test(error.message)
      ? { title: "操作未完成。", detail: error.message }
      : { title: `请求未成功（错误码 ${error.status}）。`, detail: "请重试；若持续失败，请联系维护者。", action: "刷新页面" };
  }
  return { title: "操作未完成。", detail: "请检查当前内容后重试；若持续失败，请联系维护者。", action: "刷新页面" };
}
export function errorText(error: unknown) { const message = errorMessage(error); return `${message.title} ${message.detail}`; }
